"""Index the declarations of Lean source files: full name (with the
enclosing namespaces), kind, file, line, docstring and signature, one JSON
object per line. For finding the Lean counterpart of a paper's statement by
grepping names, docstrings and signatures.

    lean_index.py DIR_OR_FILE... > index.jsonl

A source-level approximation: namespaces come from `namespace`/`section`/
`end`, a declaration's name is prefixed by them, and its signature runs to
`:=`, `where` or `|` at the start of a line. Declarations generated by Lean
(instances without names, auxiliary lemmas) are not seen; the extractor
(`imprimatur show KEY`) is the authority on what a name means.
"""
import json
import os
import re
import sys

KINDS = r"(theorem|lemma|def|abbrev|structure|inductive|class|instance|axiom|opaque)"
DECL = re.compile(r"^\s*(?:@\[[^\]]*\]\s*)?(?:(?:private|protected|noncomputable|partial|unsafe|nonrec)\s+)*"
                  + KINDS + r"\s+([^\s:({\[]+)")


def files(paths):
    for p in paths:
        if os.path.isdir(p):
            for root, dirs, fs in os.walk(p):
                dirs[:] = [d for d in dirs if d != ".lake"]
                for f in sorted(fs):
                    if f.endswith(".lean"):
                        yield os.path.join(root, f)
        else:
            yield p


def index(path):
    lines = open(path, encoding="utf-8", errors="replace").read().split("\n")
    scopes = []  # (kind, name)
    doc = None
    i = 0
    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if s.startswith("/--"):
            buf = [s]
            while "-/" not in lines[i] and i + 1 < len(lines):
                i += 1
                buf.append(lines[i].strip())
            doc = " ".join(buf)[3:].rsplit("-/", 1)[0].strip()
            i += 1
            continue
        m = re.match(r"^\s*namespace\s+(\S+)", line)
        if m:
            scopes.append(("namespace", m.group(1)))
        elif re.match(r"^\s*section\b", line):
            name = line.split()[1] if len(line.split()) > 1 else ""
            scopes.append(("section", name))
        elif re.match(r"^\s*end\b", line) and scopes:
            scopes.pop()
        m = DECL.match(line)
        if m:
            kind, name = m.group(1), m.group(2)
            if name.startswith("_root_."):
                full = name[len("_root_."):]
            else:
                ns = ".".join(n for k, n in scopes if k == "namespace")
                full = f"{ns}.{name}" if ns else name
            sig = [line.strip()]
            j = i
            while j + 1 < len(lines) and ":=" not in lines[j] and not re.match(r"^\s*(where|\|)", lines[j + 1]) \
                    and len(sig) < 40:
                j += 1
                sig.append(lines[j].strip())
            signature = " ".join(sig).split(":=")[0].strip()
            yield {"name": full, "kind": kind, "file": path, "line": i + 1,
                   "doc": doc, "signature": signature}
            doc = None
        elif s and not s.startswith("--") and not s.startswith("@["):
            doc = None if not s.startswith("/-") else doc
        i += 1


def main():
    for f in files(sys.argv[1:]):
        for d in index(f):
            print(json.dumps(d, ensure_ascii=False))


if __name__ == "__main__":
    main()

"""Generate splice/Splice/StdMacros.lean: the macros a paper may use in
generated content without defining them (DESIGN §10.3, undefined macros).

They are TeX's primitives (as LuaTeX lists them, a superset of pdfTeX's for
the names a paper uses), and the macros defined by the LaTeX kernel and its
maths fonts, the standard article class (size and sectioning commands),
amsmath, amssymb, mathpartir, and the packages imprimatur.sty loads
(longtable, newunicodechar), as found in a TeX Live installation, and by
imprimatur.sty itself. Run it from the repository root after
changing imprimatur.sty, or to pick up a newer TeX Live:

    python3 scripts/gen-std-macros.py
"""
import os
import re
import subprocess
import sys
import tempfile

# The files whose definitions count as standard, by kpsewhich name.
FILES = ["latex.ltx", "fontmath.ltx", "fonttext.ltx", "amsmath.sty", "amsopn.sty",
         "amstext.sty", "amsbsy.sty", "amsgen.sty", "amssymb.sty", "amsfonts.sty",
         "mathpartir.sty", "longtable.sty", "newunicodechar.sty",
         # The size and sectioning commands the standard classes define.
         "article.cls", "size10.clo"]
LOCAL = ["tex/imprimatur.sty"]

DEFINING = (r"def|gdef|edef|xdef|let|chardef|mathchardef|countdef|dimendef|skipdef|"
            r"toksdef|font|newcommand|renewcommand|providecommand|DeclareRobustCommand|"
            r"DeclareMathSymbol|DeclareMathAccent|DeclareMathDelimiter|DeclareMathRadical|"
            r"DeclareMathAlphabet|DeclareSymbolFontAlphabet|DeclareTextFontCommand|"
            r"DeclareOldFontCommand|DeclareMathOperator|DeclareTextCommand|DeclareTextSymbol|"
            r"DeclareTextCommandDefault|DeclareTextSymbolDefault|DeclareTextAccent|"
            r"NewDocumentCommand|DeclareDocumentCommand|newlength|newcount|newbox|newskip|"
            r"newdimen|newtoks|newif|newenvironment")
PATTERN = re.compile(r"\\(?:" + DEFINING + r")\*?\s*\{?\s*\\([A-Za-z]+)")


def primitives():
    """TeX's primitives, from LuaTeX."""
    with tempfile.TemporaryDirectory() as d:
        src = os.path.join(d, "p.tex")
        with open(src, "w") as f:
            f.write('\\directlua{local f=io.open("prims.txt","w") '
                    'for _,p in ipairs(tex.primitives()) do f:write(p,"\\string\\n") end '
                    'f:close()}\n\\bye\n')
        subprocess.run(["luatex", "-interaction=nonstopmode", "p.tex"], cwd=d,
                       capture_output=True, check=False)
        with open(os.path.join(d, "prims.txt")) as f:
            return {l.strip() for l in f if re.fullmatch(r"[A-Za-z]+", l.strip())}


def defined_in(path):
    with open(path, encoding="latin-1") as f:
        return set(PATTERN.findall(f.read()))


def main():
    names = primitives()
    for name in FILES:
        path = subprocess.run(["kpsewhich", name], capture_output=True, text=True).stdout.strip()
        if not path:
            sys.exit(f"gen-std-macros: {name} not found (kpsewhich)")
        names |= defined_in(path)
    for path in LOCAL:
        names |= defined_in(path)
    names = sorted(n for n in names if "@" not in n)
    out = ["/-",
           "Copyright (c) 2026 The imprimatur authors.",
           "Released under Apache 2.0 license as described in the file LICENSE.",
           "-/",
           "",
           "/-! Generated by `scripts/gen-std-macros.py`; do not edit. -/",
           "",
           "namespace Splice",
           "",
           "/-- Macros that generated content may use without the paper defining them:",
           "TeX's primitives, and the definitions of the LaTeX kernel, amsmath, amssymb,",
           "mathpartir and imprimatur.sty (DESIGN §10.3). -/",
           "def stdMacros : Array String := #["]
    line = "  "
    for n in names:
        item = f'"{n}", '
        if len(line) + len(item) > 96:
            out.append(line.rstrip())
            line = "  "
        line += item
    out.append(line.rstrip().rstrip(",") + "]")
    out += ["", "end Splice", ""]
    with open("splice/Splice/StdMacros.lean", "w") as f:
        f.write("\n".join(out))
    print(f"gen-std-macros: {len(names)} macros")


if __name__ == "__main__":
    main()

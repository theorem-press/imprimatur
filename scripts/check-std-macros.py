"""lint/std-macros: splice/Splice/StdMacros.lean knows every macro tex/imprimatur.sty
defines (DESIGN §10.3). The list is generated by scripts/gen-std-macros.py,
which needs a TeX Live installation; this check needs none, so it runs in the
lint job and fails when imprimatur.sty gains a macro the list lacks, as
\\LeanSourceRef did (#128). Fix: python3 scripts/gen-std-macros.py.
"""
import importlib.util
import os
import re
import sys

# Importing the generator must leave no __pycache__ in scripts/, which other lint
# checks read as text.
sys.dont_write_bytecode = True
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
spec = importlib.util.spec_from_file_location(
    "gen_std_macros", os.path.join(ROOT, "scripts", "gen-std-macros.py"))
gen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen)


def main():
    defined = set()
    for path in gen.LOCAL:
        defined |= gen.defined_in(os.path.join(ROOT, path))
    defined = {n for n in defined if "@" not in n}
    with open(os.path.join(ROOT, "splice", "Splice", "StdMacros.lean")) as f:
        listed = set(re.findall(r'"([A-Za-z]+)"', f.read()))
    missing = sorted(defined - listed)
    if missing:
        print("lint/std-macros: imprimatur.sty defines macros splice/Splice/StdMacros.lean "
              "does not list: " + ", ".join("\\" + m for m in missing))
        print("  regenerate the list: python3 scripts/gen-std-macros.py")
        return 1
    print(f"lint/std-macros: {len(defined)} macros of imprimatur.sty listed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
